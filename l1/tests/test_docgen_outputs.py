def test_front_pages_share_readme_tagline():
    templates = ROOT / 'scripts/docs/templates'
    tagline = (templates / 'tagline.txt.j2').read_text().strip()
    env = Environment(loader=FileSystemLoader(templates))
    for name in ('mainpage_html.md.j2', 'mainpage_latex.md.j2', 'markdown_index.md.j2'):
        text = env.get_template(name).render(compiler=[], shared=[])
        assert f'*{tagline}*' in text
        assert 'small safe C-family' not in text
    for name in ('README.md', 'docs/user/README.md'):
        lines = (ROOT / name).read_text().splitlines()
        quote = ' '.join(line.removeprefix('> ').strip() for line in lines if line.startswith('>'))
        assert quote == f'_{tagline}_'


def test_pdf_cover_tagline_preserves_metadata_and_escapes_text():
    original = r'''\begin{titlepage}
  \begin{center}%
  {\Large Dea/L1 API}\\
  [1ex]\large Generated 2026-10-12 l0docgenlinetwo development \\
  \vspace*{1cm}
  {\large Generated by Doxygen}\\
  \end{center}
  \end{titlepage}
'''
    result = _normalize_titlepage_front_matter(original, 'Arrays & slices_1.')
    assert r'Arrays \& slices\_1.' in result
    assert 'l0docgenlinetwo' not in result
    assert r'[1ex]\large Generated 2026-10-12 \\' in result
    assert r'\large development \\' in result
    assert result.index('Arrays') < result.index('Generated by Doxygen')
    assert _normalize_titlepage_front_matter(result, 'Arrays & slices_1.') == result
    with pytest.raises(ValueError, match='insertion point'):
        _normalize_titlepage_front_matter('Unexpected Doxygen cover', 'Tagline.')


