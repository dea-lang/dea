/**
 * Construct an entropy failure retaining the successfully completed prefix.
 *
 * @param count Number of bytes completed before the failed native operation.
 * @param error Captured error independent of ambient native error state.
 * @return Failure with the known completed prefix and supplied native error.
 */
static struct __deaM3sys2osS10RtIoResult entropy_failure(
    dea_int count, struct __deaM3sys2osS9RtOsError error
) {
    return (struct __deaM3sys2osS10RtIoResult){DEA_IO_FAILED, count, error};
}

/**
 * Construct an entropy failure without inventing a native error code.
 *
 * @param count Number of bytes completed before detecting the failure.
 * @param kind Normalized runtime failure category.
 * @return Failure in the Runtime namespace with native code zero.
 */
static struct __deaM3sys2osS10RtIoResult entropy_runtime_failure(dea_int count, dea_int kind) {
    return entropy_failure(count, (struct __deaM3sys2osS9RtOsError){
        kind, DEA_OS_DOMAIN_RUNTIME, 0});
}

#if defined(_WIN32)

/**
 * Preserve a BCrypt NTSTATUS code in its own unsigned native namespace.
 *
 * @param status Native signed NTSTATUS failure whose 32-bit pattern is retained.
 * @return Normalized error with the unsigned code widened to a Dea long.
 */
static struct __deaM3sys2osS9RtOsError entropy_ntstatus_error(LONG status) {
    uint32_t code = (uint32_t)status;
    dea_int kind = DEA_OS_ERROR_OTHER;
    switch (code) {
    case UINT32_C(0xc0000002):
    case UINT32_C(0xc00000bb): kind = DEA_OS_ERROR_UNSUPPORTED; break;
    case UINT32_C(0xc0000008): kind = DEA_OS_ERROR_INVALID_HANDLE; break;
    case UINT32_C(0xc000000d): kind = DEA_OS_ERROR_INVALID_INPUT; break;
    case UINT32_C(0xc0000017): kind = DEA_OS_ERROR_OUT_OF_MEMORY; break;
    case UINT32_C(0xc0000022): kind = DEA_OS_ERROR_PERMISSION_DENIED; break;
    case UINT32_C(0xc000009a): kind = DEA_OS_ERROR_RESOURCE_EXHAUSTED; break;
    }
    return (struct __deaM3sys2osS9RtOsError){kind, DEA_OS_DOMAIN_NTSTATUS, (dea_long)code};
}
#endif

/**
 * Fill caller-owned bytes from the operating system's secure entropy source.
 *
 * Zero count succeeds without inspecting storage or calling the host. Positive
 * requests use at most 256 bytes per native operation. Linux, FreeBSD, and
 * NetBSD use getrandom with GRND_NONBLOCK; Apple and OpenBSD use getentropy.
 * Windows resolves BCryptGenRandom only through the System32 search policy and
 * selects the system-preferred RNG. Unsupported hosts fail without a fallback.
 * Native interruption and unavailable entropy are returned without retry.
 *
 * Successful short reads are continued. Native calls write a temporary chunk,
 * copied to the destination only after successful completion. Failure reports
 * the exact completed prefix and leaves the remaining destination unchanged.
 * Bytes outside the requested range are never modified. No pointer is retained
 * and no ownership transfers. Neither storage nor generated bytes are securely
 * erased. Windows loader resources are acquired and released per positive call;
 * their native costs are separate from Dea heap allocation.
 *
 * @param buf Writable storage for count bytes; ignored when count is zero.
 * @param count Nonnegative requested byte count; positive count requires buf.
 * @return Full success or captured failure with the known completed prefix.
 */
struct __deaM3sys2osS10RtIoResult rt_entropy_fill(void *buf, dea_int count) {
    dea_int done = 0;
    if (count < 0 || (count > 0 && buf == NULL))
        return entropy_runtime_failure(0, DEA_OS_ERROR_INVALID_INPUT);
    if (count == 0)
        return (struct __deaM3sys2osS10RtIoResult){DEA_IO_OK, 0, {0, DEA_OS_DOMAIN_RUNTIME, 0}};
#if defined(_WIN32)
    HMODULE module = DEA_ENTROPY_LOAD_LIBRARY(L"bcrypt.dll", NULL, LOAD_LIBRARY_SEARCH_SYSTEM32);
    if (module == NULL) {
        DWORD code = GetLastError();
        return entropy_failure(0, rt_os_error_from_win32((dea_long)code));
    }
    DeaEntropyGenerate generate = (DeaEntropyGenerate)(void (*)(void))
        DEA_ENTROPY_GET_PROC(module, "BCryptGenRandom");
    if (generate == NULL) {
        DWORD code = GetLastError();
        DEA_ENTROPY_FREE_LIBRARY(module);
        return entropy_failure(0, rt_os_error_from_win32((dea_long)code));
    }
#endif
    while (done < count) {
        unsigned char bytes[256];
        dea_int chunk = count - done;
        if (chunk > 256) chunk = 256;
#if defined(_WIN32)
        LONG status = generate(NULL, bytes, (ULONG)chunk, DEA_ENTROPY_SYSTEM_PREFERRED_RNG);
        if (status < 0) {
            struct __deaM3sys2osS9RtOsError error = entropy_ntstatus_error(status);
            DEA_ENTROPY_FREE_LIBRARY(module);
            return entropy_failure(done, error);
        }
#elif defined(__linux__) || defined(__FreeBSD__) || defined(__NetBSD__)
        ssize_t transferred = DEA_ENTROPY_GETRANDOM(bytes, (size_t)chunk, GRND_NONBLOCK);
        if (transferred < 0) {
            int code = errno;
            return entropy_failure(done, rt_os_error_from_errno(code));
        }
        if (transferred == 0 || transferred > chunk)
            return entropy_runtime_failure(done, DEA_OS_ERROR_IO_ERROR);
        chunk = (dea_int)transferred;
#elif defined(__APPLE__) || defined(__OpenBSD__)
        if (DEA_ENTROPY_GETENTROPY(bytes, (size_t)chunk) != 0) {
            int code = errno;
            return entropy_failure(done, rt_os_error_from_errno(code));
        }
#else
        return entropy_runtime_failure(0, DEA_OS_ERROR_UNSUPPORTED);
#endif
        memcpy((unsigned char *)buf + done, bytes, (size_t)chunk);
        done += chunk;
    }
#if defined(_WIN32)
    DEA_ENTROPY_FREE_LIBRARY(module);
#endif
    return (struct __deaM3sys2osS10RtIoResult){DEA_IO_OK, done, {0, DEA_OS_DOMAIN_RUNTIME, 0}};
}
